import {readFile,writeFile,readdir,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url)),repo=path.resolve(root,'../..');
const sources=(await readdir(path.join(root,'src'))).filter(n=>n.endsWith('.ts')&&n!=='build-info.ts').sort();
const hash=createHash('sha256');for(const name of sources)hash.update(name+'\0').update(await readFile(path.join(root,'src',name)));
const build=hash.digest('hex');
await writeFile(path.join(root,'src/build-info.ts'),`// Generated by scripts/build.mjs from the canonical source files.\nexport const ENGINE_BUILD = '${build}';\n`);
execFileSync(process.execPath,[path.join(repo,'node_modules/typescript/bin/tsc'),'-p',path.join(root,'tsconfig.json')],{stdio:'inherit'});
// Existing research/check tools can keep their import paths. These files contain
// no simulation logic: both Node and the local browser resolve to this build.
const compatibility=path.join(repo,'deliverables/football-practice/engine-audition/local-five-sandbox/runtime');
await mkdir(compatibility,{recursive:true});
for(const name of sources){const js=name.replace(/\.ts$/,'.js');await writeFile(path.join(compatibility,js),`// Compatibility import. Edit packages/football-engine/src instead.\nexport * from '../../../../../packages/football-engine/dist/${js}';\n`);}
console.log(`Football engine ${build.slice(0,12)} built.`);
